    public Checkout() {
        initComponents();
        
        DB db = new DB();
        
        // Get user input
                String username = TFUser.getText();
                String date = TFDate.getText();
                String price = new String(TextAreaPrice.getText());
                String pay = TFPayment.getText();
                String collect = TFcollect.getText();
                String hirebuy = TFhb.getText();
                
                
                try {
                    
                    CheckoutDBManager.db.update("INSERT INTO UserCheckoutBuy (Username, PurchaseDate, PaymentMethod, TotalPrice, Collection, PurchaseType ) VALUES ('" + username + "', '" + date + "', '" + pay + "', '" 
                            + price + "', '" + collect + "', '" + hirebuy + "')");
                    /* Optionally, you can display a success message or navigate to the next JFrame
                    JOptionPane.showMessageDialog(null, "Checkout successful!", "Success", JOptionPane.INFORMATION_MESSAGE);*/
                } catch (SQLException ex) {
                    // Handle database update error
                    ex.printStackTrace();
                    JOptionPane.showMessageDialog(null, "Failed to save checkout information!", "Database Error", JOptionPane.ERROR_MESSAGE);
                }
                
                
                
        try 
        {
            Scanner myfile = new Scanner (new File("Basket.JSON"));
            if (myfile.hasNextLine()) 
            {
              myfile.nextLine(); // Skip JSON line
            }
            
            // Read the plain text part (assuming it's on the second line)
            String line = myfile.nextLine();
            
            
            
            // Split the plain text part to extract Quantity and Price
            String[] parts = line.split("\\t");  // splits by tab character
            int quantity = Integer.parseInt(parts[0].split(": ")[1]);  // Extracts "55"
            double price2 = Double.parseDouble(parts[1].split(": ")[1]);  // Extracts "780"

            // Calculate total price (assuming you multiply price by quantity)
            double totalPrice = quantity * price2;

            // Output the total price
            TextAreaPrice.append("" + totalPrice);
         
        }
        catch (IOException e) 
        {
            e.printStackTrace();
        }
    }
    


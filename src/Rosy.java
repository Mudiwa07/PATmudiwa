    private void BtBasket3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtBasket3ActionPerformed
        // TODO add your handling code here:
        BManager manager = new BManager("Basket.json");
        
        // Optionally clear the basket
        int option = JOptionPane.showConfirmDialog(null, "Clear your basket and start new session?", "Clear Basket", JOptionPane.YES_NO_OPTION);
        if (option == JOptionPane.YES_OPTION) {
            manager.clearBasket();
        }
        // Add items interactively
        manager.interactiveAddItems();
        
        String quant = BSquantfield.getText();
        String price = Price.getText();
        try(PrintWriter outFile = new PrintWriter( new FileWriter("Basket.json", true)))
        {
    
          String line = quant;
          String line2 = price;
          outFile.println("\nQuantity: " + line + "\tPrice: "+ line2 + "\n");
      
        }
   catch (IOException f)
   {
     System.out.println ("File Not Found");
   }
    }//GEN-LAST:event_BtBasket3ActionPerformed

